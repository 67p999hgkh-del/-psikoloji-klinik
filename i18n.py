def translate(key, lang="tr", **kwargs):
    lang = lang if lang in TRANSLATIONS else "tr"
    text = TRANSLATIONS[lang].get(key) or TRANSLATIONS["tr"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text

def _test_from_item(item, PsychologicalTest):
    benefits = item.get("benefits", DEFAULT_BENEFITS)
    return PsychologicalTest(
        title=item["title"],
        slug=item["slug"],
        description=item["description"],
        category=item["category"],
        icon=item["icon"],
        source_note=item["source_note"],
        seo_title=item.get("seo_title", ""),
        seo_description=item.get("seo_description", ""),
        seo_keywords=item.get("seo_keywords", ""),
        hero_title=item.get("hero_title", ""),
        hero_subtitle=item.get("hero_subtitle", ""),
        duration_minutes=item.get("duration_minutes", 5),
        accent_color=item.get("accent_color", "#2d6a6a"),
        benefits=json.dumps(benefits, ensure_ascii=False),
        match_tags=item.get("match_tags", ""),
        test_group=item.get("test_group", "mood"),
        available_langs=item.get("available_langs", "tr,en,de"),
        scoring_type=item["scoring_type"],
        sort_order=item["sort_order"],
        questions=json.dumps(item["questions"], ensure_ascii=False),
        is_active=True,
    )


def _sync_test(existing, item):
    existing.title = item["title"]
    existing.description = item["description"]
    existing.category = item["category"]
    existing.icon = item["icon"]
    existing.source_note = item["source_note"]
    existing.seo_title = item.get("seo_title", existing.seo_title or "")
    existing.seo_description = item.get("seo_description", existing.seo_description or "")
    existing.seo_keywords = item.get("seo_keywords", existing.seo_keywords or "")
    existing.hero_title = item.get("hero_title", existing.hero_title or "")
    existing.hero_subtitle = item.get("hero_subtitle", existing.hero_subtitle or "")
    existing.duration_minutes = item.get("duration_minutes", existing.duration_minutes or 5)
    existing.accent_color = item.get("accent_color", existing.accent_color or "#2d6a6a")
    existing.benefits = json.dumps(item.get("benefits", DEFAULT_BENEFITS), ensure_ascii=False)
    existing.match_tags = item.get("match_tags", existing.match_tags or "")
    existing.test_group = item.get("test_group", existing.test_group or "mood")
    existing.available_langs = item.get("available_langs", existing.available_langs or "tr,en,de")
    existing.scoring_type = item["scoring_type"]
    existing.sort_order = item["sort_order"]
    existing.questions = json.dumps(item["questions"], ensure_ascii=False)


def seed_psychological_tests(db, PsychologicalTest):
    if PsychologicalTest.query.first():
        return
    for item in DEFAULT_TESTS:
        db.session.add(_test_from_item(item, PsychologicalTest))
    db.session.commit()


def upgrade_psychological_tests(db, PsychologicalTest):
    changed = False
    for item in DEFAULT_TESTS:
        existing = PsychologicalTest.query.filter_by(slug=item["slug"]).first()
        if existing:
            _sync_test(existing, item)
            changed = True
        else:
            db.session.add(_test_from_item(item, PsychologicalTest))
            changed = True
    if changed:
        db.session.commit()
